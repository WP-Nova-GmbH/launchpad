import * as NodeServices from "@effect/platform-node/NodeServices";
import { assert, it } from "@effect/vitest";
import * as Effect from "effect/Effect";
import * as FileSystem from "effect/FileSystem";
import * as Layer from "effect/Layer";
import * as Path from "effect/Path";
import { ProcessRunner, layer as ProcessRunnerLayer } from "../processRunner.ts";
import {
  exportWorkflowVmFollowUpBundle,
  verifyWorkflowVmFollowUpBundle,
} from "./WorkflowVmFollowUpGit.ts";
import { workflowVmPublishingGit } from "./WorkflowVmPublishingGit.ts";

it.effect("retains only the exact follow-up commits and verifies the expected ancestry", () =>
  Effect.gen(function* () {
    const fs = yield* FileSystem.FileSystem;
    const path = yield* Path.Path;
    const runner = yield* ProcessRunner;
    const worktreePath = yield* fs.makeTempDirectoryScoped({ prefix: "follow-up-worktree-" });
    const protectedPath = yield* fs.makeTempDirectoryScoped({ prefix: "follow-up-protected-" });
    const checkout = (args: ReadonlyArray<string>, options?: { allowNonZero?: boolean }) =>
      runner.run({ command: "/usr/bin/git", args, cwd: worktreePath }).pipe(
        Effect.map((result) => {
          assert.isTrue(result.code === 0 || options?.allowNonZero === true, result.stderr);
          return result.stdout.trim();
        }),
      );
    const write = (file: string, content: string) =>
      fs.writeFileString(path.join(worktreePath, file), content);
    const commit = (message: string) =>
      checkout(["add", "--all"]).pipe(
        Effect.andThen(checkout(["commit", "-m", message])),
        Effect.andThen(checkout(["rev-parse", "HEAD"])),
      );
    const git = workflowVmPublishingGit(runner, protectedPath, "example/repository");
    yield* checkout(["init", "--initial-branch=main"]);
    yield* checkout(["config", "user.name", "Follow Up"]);
    yield* checkout(["config", "user.email", "dev@example.test"]);
    yield* checkout(["config", "commit.gpgSign", "false"]);
    yield* write("base.txt", "base");
    const baseSha = yield* commit("base");
    yield* write("workflow.txt", "generated by the workflow");
    const agentSha = yield* commit("transient agent history");
    const treeSha = yield* checkout(["rev-parse", "HEAD^{tree}"]);
    const baseline = yield* checkout([
      "commit-tree",
      treeSha,
      "-p",
      baseSha,
      "-m",
      "Workflow result",
    ]);
    yield* checkout(["update-ref", "refs/heads/launchpad/job", baseline]);
    yield* checkout(["switch", "launchpad/job"]);
    yield* runner.run({ command: "/usr/bin/git", args: ["init", "--bare"], cwd: protectedPath });
    assert.strictEqual(
      (yield* runner.run({
        command: "/usr/bin/git",
        args: [
          "--git-dir",
          protectedPath,
          "fetch",
          "--no-tags",
          worktreePath,
          "refs/heads/launchpad/job:refs/heads/launchpad/job",
        ],
        cwd: protectedPath,
      })).code,
      0,
    );
    yield* write("first.txt", "first follow-up");
    const first = yield* commit("first follow-up");
    yield* write("second.txt", "second follow-up");
    const sha = yield* commit("second follow-up");
    yield* write("dirty.txt", "keep out of the push");
    const bundle = yield* exportWorkflowVmFollowUpBundle(
      { checkout, worktreePath, runner },
      sha,
      baseline,
      null,
    );
    const input = { git, worktreePath, run: { baseSha } };
    yield* verifyWorkflowVmFollowUpBundle(input, { bundle, sha, baseline, oldRemoteSha: null });
    const { stdout: newCommits } = yield* git.git(["rev-list", `${baseline}..${sha}`]);
    assert.deepStrictEqual(newCommits.trim().split("\n"), [sha, first]);
    const { stdout: names } = yield* git.git(["ls-tree", "--name-only", sha]);
    assert.deepStrictEqual(names.trim().split("\n"), [
      "base.txt",
      "first.txt",
      "second.txt",
      "workflow.txt",
    ]);
    assert.notStrictEqual(
      (yield* git.git(["cat-file", "-e", agentSha], { allowNonZero: true })).code,
      0,
    );
    assert.strictEqual(
      (yield* git.git(["show", "-s", "--format=%ae", sha])).stdout.trim(),
      "dev@example.test",
    );
    assert.isTrue(
      yield* Effect.isFailure(
        verifyWorkflowVmFollowUpBundle(input, {
          bundle,
          sha: first,
          baseline,
          oldRemoteSha: null,
        }),
      ),
    );
    assert.isTrue(
      yield* Effect.isFailure(
        verifyWorkflowVmFollowUpBundle(input, {
          bundle,
          sha,
          baseline,
          oldRemoteSha: agentSha,
        }),
      ),
    );
  }).pipe(Effect.provide(ProcessRunnerLayer.pipe(Layer.provideMerge(NodeServices.layer)))),
);
